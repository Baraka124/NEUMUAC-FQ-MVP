import type {VariantTherapyProfile} from './therapyRegistry';
import type {ClassIReviewFinding} from './classIReviewSignals';
import {getTherapy} from './therapyRegistry';
import {historicalFlagFindings} from './historicalModulatorFlags';

/** A portable, nonidentifying research worklist entry. It is not a clinical
 * decision, approval, uploaded document, or writable Helios record.
 */
function safe(value:string|null):string{
 return (value??'Not recorded').replace(/[\r\n\t]+/g,' ').replace(/[\\`*_{}\[\]<>|]/g,'').slice(0,320);
}
export function buildTherapyReviewBrief(
 profile:VariantTherapyProfile,signals:readonly ClassIReviewFinding[]
):string{
 if(!/^[1-9]\d{0,17}$/.test(profile.variantId))throw new Error('Invalid variant');
 if(profile.entries.length!==5||new Set(profile.entries.map(e=>e.therapy)).size!==5)
  throw new Error('Incomplete five-therapy profile');
 const lines=[
  '# CFTR modulator evidence review',
  '',
  'Variant record ID: '+profile.variantId,
  'CFTR class: '+safe(profile.functionalClass),
  'Class subtype: '+safe(profile.classSubtype),
  'Recorded validation count: '+(profile.validationCount===null?'Not recorded':profile.validationCount),
  '',
  '## Therapies'
 ];
 for(const entry of profile.entries){
  const therapy=getTherapy(entry.therapy);
  lines.push('- '+therapy.label+': '+(entry.coverage==='variant-response'?
   safe(entry.response==='non_responsive'?'non-responsive':entry.response):'Genotype rules only')+
   (entry.coverage==='variant-response'?' | evidence level: '+safe(entry.evidenceLevel)+
     ' | tier: '+safe(entry.evidenceTier)+' | source label: '+safe(entry.authoritySource):''));
 }
 lines.push('','## Historical drug flags (recorded data, not a therapeutic conclusion)');
 for(const finding of historicalFlagFindings(profile)){
  const value=finding.flag===true?'Yes':finding.flag===false?'No':'Not recorded';
  lines.push('- '+getTherapy(finding.therapy).label+': '+value+
   (finding.state==='different-recorded-fields'?' | differs from the recorded response category':''));
 }
 lines.push('','## Review prompts');
 if(!signals.length)lines.push('- No Class I review prompts generated by the current rule set.');
 else for(const signal of signals)lines.push('- '+safe(signal.message));
 lines.push('','Source records and review decisions must be examined in the linked evidence and validation workspaces.');
 return lines.join('\n')+'\n';
}
